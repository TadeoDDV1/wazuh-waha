"""Tests para el endpoint de reportes PDF por agente."""
import unittest

from fastapi.testclient import TestClient

from relay.wazuh_waha.config import settings
from relay.wazuh_waha.main import app

AUTH = {"X-Api-Key": settings.relay_api_key}


class TestReportsEndpoint(unittest.TestCase):
    def setUp(self):
        self.client = TestClient(app)

    def test_report_requires_auth(self):
        r = self.client.get("/api/v1/reports/agent/000")
        self.assertEqual(r.status_code, 401)

    def test_report_returns_pdf(self):
        r = self.client.get("/api/v1/reports/agent/000", headers=AUTH)
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r.headers["content-type"], "application/pdf")
        self.assertTrue(r.content[:5] == b"%PDF-", "Response is not a valid PDF")

    def test_report_has_content_disposition(self):
        r = self.client.get("/api/v1/reports/agent/000", headers=AUTH)
        cd = r.headers.get("content-disposition", "")
        self.assertIn("attachment", cd)
        self.assertIn("reporte_agente_000", cd)
        self.assertIn(".pdf", cd)

    def test_report_cache_no_store(self):
        r = self.client.get("/api/v1/reports/agent/000", headers=AUTH)
        self.assertEqual(r.headers.get("cache-control"), "no-store")


